#!/usr/bin/env bash
# Rebuilds every image under assets/ from the game repository's own code and committed art.
#
#     scripts/make-images.sh                      uses ../half_court_duo
#     scripts/make-images.sh /path/to/game/repo   uses <that>
#
# WHERE THE PICTURES COME FROM, AND WHY IT MATTERS. Every image on this site is something the game
# drew: the site's logo is `swift run hcd-art marketing-icon --design 4`, rendered here from the game's
# code, the badges are `swift run hcd-art badges` (committed in marketing/), and the screenshots are
# `-halfcourt-showcase` launches of the real app frozen on one scripted moment, seated in a folded phone
# that the game repository's composer draws in HTML and CSS (committed in marketing/). Nothing here is
# downloaded, traced, generated by a model or painted over. The game's house rule (no AI art, no
# downloaded or bundled assets) applies to its website for the same reason it applies to the app: a
# picture of the product that the product did not make is a claim about the product.
#
# THE SITE'S LOGO IS NOT THE APP'S ICON. The owner chose two of the five icon options the game draws
# (the game repository's decision 240, 25 October 2026): option 3, "Across the Fold", is the app icon
# and the App Store icon (marketing/app-icon-1024.png there), and option 4, "Neon Swish", is this
# site's logo: the favicon, the home screen icon a visitor saves, the mark in every page's header, the
# hero and the share card. The game ships option 4 nowhere, so there is no committed file to copy;
# hcd-art draws it from IconDesign.neonSwish, which is reproducible, and the 1024 it writes is opaque
# RGB like the store icon. Never copy marketing/app-icon-1024.png here: that is the other picture.
#
# THE SCREENSHOTS LOSE THEIR CAPTIONS. The App Store pictures carry a headline and a subtitle drawn into
# the raster above the phone. On this site those words would sit beside the page's own prose saying the
# same thing twice, and words inside a PNG are invisible to grep, to a diff and to scripts/lint-site.py,
# which is how a sibling site's share card went on announcing a date a month after it had passed. So
# each picture is cut just below its caption, keeping the drawn phone whole, and the page says in text
# what the caption said. The cut is a pixel row per slot, measured on the committed pictures; if the
# composer's caption height ever changes, re-measure (render one at full size and look) and change the
# three numbers below.
#
# THE CUT IS DONE BY HEADLESS BRAVE, NOT SIPS. `sips --cropOffset` ignores its offset or applies it
# from somewhere other than the top edge, depending on the order of its arguments, and both came out
# looking plausible. A browser told to draw the picture 440 px up inside a window of the right size
# is exact, and it is the renderer the game repository's composer already uses. Local files only: the
# window is a file:// page and nothing is fetched.
#
# Run it after the game's marketing art changes, look at what it wrote, and commit both.
set -euo pipefail

SITE="$(cd "$(dirname "$0")/.." && pwd)"
GAME="$(cd "${1:-$SITE/../half_court_duo}" && pwd)" || { echo "make-images: no game repository there"; exit 1; }
ART="$(cd "$GAME/marketing" && pwd)" || { echo "make-images: no marketing/ under $GAME"; exit 1; }
LOGO_DESIGN=4     # IconDesign.neonSwish, the owner's choice for the website (decision 240)

# The game builds only with the Xcode seed (its CLAUDE.md, "Toolchain"); never xcode-select, which
# is global. An explicit DEVELOPER_DIR is respected.
: "${DEVELOPER_DIR:=/Applications/Xcode-beta.app/Contents/Developer}"
export DEVELOPER_DIR
BRAVE="/Applications/Brave Browser.app/Contents/MacOS/Brave Browser"
[ -x "$BRAVE" ] || { echo "make-images: headless Brave not found at $BRAVE"; exit 1; }

WORK="$(mktemp -d -t hcd-images)"
trap 'rm -rf "$WORK"' EXIT

# Pixel rows to cut from the top of each slot's framed picture: below the caption, above the phone.
CUT_INNER=440     # duo-inner, 2007 x 2853: caption ends near 362, the phone's top edge near 532
CUT_COVER=236     # duo-cover, 1398 x 2034: caption ends near 160, the phone near 314
CUT_PHONE=222     # iphone,    1320 x 2868: caption ends near 196, the phone near 253

# Draws $1 shifted up by $2 px into a window $3 x $4, then scales to $5 px wide as JPEG at $6.
crop() {
    local src="$1" cut="$2" w="$3" h="$4" width="$5" out="$6"
    local page="$WORK/crop.html" png="$WORK/crop.png"
    printf '<!doctype html><html><body style="margin:0;background:#0B1020">' > "$page"
    printf '<img src="file://%s" style="display:block;margin-top:-%spx"></body></html>' "$src" "$cut" >> "$page"
    rm -f "$png"
    "$BRAVE" --headless --disable-gpu --hide-scrollbars --no-first-run --disable-background-networking \
        --disable-component-update --disable-sync --force-device-scale-factor=1 \
        --window-size="$w,$((h - cut))" --screenshot="$png" "file://$page" >/dev/null 2>&1
    [ -s "$png" ] || { echo "make-images: Brave wrote nothing for $src"; exit 1; }
    sips --resampleWidth "$width" -s format jpeg -s formatOptions 78 "$png" --out "$out" >/dev/null
    printf '  %-40s %6s bytes\n' "${out#"$SITE/"}" "$(stat -f%z "$out")"
}

mkdir -p "$SITE/assets/shots" "$SITE/assets/poses" "$SITE/assets/badges"

echo "logo: option $LOGO_DESIGN, drawn by the game's hcd-art"
# Each size is named for its pixels, and each has one job: 32 the favicon, 96 the header's mark (drawn
# at 30 css px, so sharp at 3x), 180 the apple-touch-icon iOS puts on a home screen (opaque, square: iOS
# rounds it), 256 the hero's mark (drawn at 88 css px) and the share card's (112 px).
( cd "$GAME" && swift run --quiet hcd-art marketing-icon "$WORK/logo-1024.png" --design "$LOGO_DESIGN" ) \
    || { echo "make-images: hcd-art failed in $GAME"; exit 1; }
[ -s "$WORK/logo-1024.png" ] || { echo "make-images: hcd-art wrote no logo"; exit 1; }
size="$(sips -g pixelWidth -g pixelHeight -g hasAlpha "$WORK/logo-1024.png" | awk 'NR>1 {printf "%s ", $2}')"
[ "$size" = "1024 1024 no " ] || { echo "make-images: the logo is '$size', expected 1024 1024 with no alpha"; exit 1; }
for px in 32 96 180 256; do
    sips -z "$px" "$px" "$WORK/logo-1024.png" --out "$SITE/assets/logo-$px.png" >/dev/null
    printf '  %-40s %6s bytes\n' "assets/logo-$px.png" "$(stat -f%z "$SITE/assets/logo-$px.png")"
done

echo "screenshots: the laptop pose, the seven store scenes"
for f in "$ART"/screenshots-framed/duo-inner/duo-inner-0*.png; do
    slug="$(basename "$f" .png)"; slug="${slug#duo-inner-}"
    crop "$f" "$CUT_INNER" 2007 2853 640 "$SITE/assets/shots/$slug.jpg"
done

echo "poses: the closed phone and a phone without a fold"
crop "$ART/screenshots-framed/duo-cover/duo-cover-01-hero.png" "$CUT_COVER" 1398 2034 560 "$SITE/assets/poses/closed.jpg"
crop "$ART/screenshots-framed/iphone/iphone-01-hero.png" "$CUT_PHONE" 1320 2868 400 "$SITE/assets/poses/no-fold.jpg"

echo "badges: the fifteen Game Center achievements"
for f in "$ART"/achievements/*.png; do
    out="$SITE/assets/badges/$(basename "$f" .png).jpg"
    sips -z 192 192 -s format jpeg -s formatOptions 82 "$f" --out "$out" >/dev/null
    printf '  %-40s %6s bytes\n' "${out#"$SITE/"}" "$(stat -f%z "$out")"
done

echo "done. Look at them before committing; then scripts/make-og.sh if the logo or the hero picture changed."
